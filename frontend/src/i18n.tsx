const messages: Record<Locale, Record<MessageKey, string>> = { "zh-CN": zhCN, en, "zh-TW": zhTW }
const storageKey = "laya-server-locale"

export function resolveLocale(languages: readonly string[]): Locale {
  for (const language of languages) {
    const value = language.toLowerCase()
    if (value.startsWith("zh-hant") || /^zh-(tw|hk|mo)(-|$)/.test(value)) return "zh-TW"
    if (value.startsWith("zh")) return "zh-CN"
    if (value.startsWith("en")) return "en"
  }
  return "en"
}

function initialLocale(): Locale {
  try {
    const stored = localStorage.getItem(storageKey)
    if (stored === "zh-CN" || stored === "zh-TW" || stored === "en") return stored
  } catch { /* Storage may be unavailable in private browsing. */ }
  return resolveLocale(navigator.languages?.length ? navigator.languages : [navigator.language])
}

export type Translate = (key: MessageKey, values?: Record<string, string | number>) => string
type I18nContextValue = { locale: Locale; setLocale: (locale: Locale) => void; t: Translate }
const I18nContext = createContext<I18nContextValue | null>(null)

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocale] = useState<Locale>(initialLocale)
  useEffect(() => {
    document.documentElement.lang = locale
    try { localStorage.setItem(storageKey, locale) } catch { /* Keep the in-memory selection. */ }
  }, [locale])
  const t: Translate = (key, values) => messages[locale][key].replace(/\{(\w+)\}/g, (match, name: string) => String(values?.[name] ?? match))
  return <I18nContext.Provider value={{ locale, setLocale, t }}>{children}</I18nContext.Provider>
}

export function useI18n(): I18nContextValue {
  const context = useContext(I18nContext)
  if (!context) throw new Error("I18nProvider is missing")
  return context
}

const errorMessages: Record<string, MessageKey> = {
  VALIDATION_ERROR: "errorValidation",
  ORIGIN_MISMATCH: "errorOrigin",
  UNAUTHENTICATED: "errorUnauthenticated",
  CSRF_INVALID: "errorCsrf",
  INVALID_API_KEY: "errorInvalidKey",
  MODEL_UNAVAILABLE: "errorModelUnavailable",
  USAGE_UNAVAILABLE: "errorUsageUnavailable",
  LOGIN_RATE_LIMITED: "errorLoginRateLimited",
  INVALID_CREDENTIALS: "errorInvalidCredentials",
  KEY_NOT_FOUND: "errorKeyNotFound",
}

export function apiErrorMessage(code: string | undefined, t: Translate): string {
  return t((code && errorMessages[code]) || "errorGeneric")
}
